// Helper to get feature translation with fallback
export const getFeatureTranslation = (key: string, language: string): string => {
  const lang = language as keyof typeof featureTranslations;
  const translations = featureTranslations[lang] || featureTranslations.en;
  return (translations as Record<string, string>)[key] || (featureTranslations.en as Record<string, string>)[key] || key;
};
